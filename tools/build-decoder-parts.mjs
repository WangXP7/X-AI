// Part hashes are pinned to the shipped binary; browser cache contents are untrusted.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {DECODER_ASSETS} from '../src/decoder-assets.js';
const asset=DECODER_ASSETS.find(a=>a.name==='wasm'),size=1048576;
const bytes=await readFile(new URL(asset.path,new URL('../src/decoder-assets.js',import.meta.url)));
if(bytes.length!==asset.bytes||createHash('sha256').update(bytes).digest('hex')!==asset.sha256)throw Error('Shipped WASM does not match the decoder manifest.');
const hashes=[];for(let i=0;i<bytes.length;i+=size)hashes.push(createHash('sha256').update(bytes.subarray(i,i+size)).digest('hex'));
await writeFile(new URL('../src/decoder-parts.js',import.meta.url),`// Generated by tools/build-decoder-parts.mjs from the verified shipped WASM.\nexport const DECODER_PART_SIZE=${size};\nexport const DECODER_PART_HASHES=${JSON.stringify(hashes,null,2)};\n`);
